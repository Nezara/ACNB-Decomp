def main():
    tool, objdir, out, report = sys.argv[1:5]
    os.makedirs(out, exist_ok=True)
    for f in glob.glob(os.path.join(out, "stub_*.cpp")):
        os.remove(f)
    defined, undef = nm(tool, sorted(glob.glob(os.path.join(objdir, "*.o"))))
    undef["_main"].add("sourceport/main")   # the host entry calls the game's main()
    need = {s: users for s, users in undef.items() if s not in defined and s not in HOST_DEFINED}
    data, funcs = data_index(), func_index()
    # sp_tables: tables still needed + every symbol they point to (stubbed / defined like any other reference)
    tabs, todo = set(), [s for s in need if s in sp_tables.CODE or s in sp_tables.ELF]
    while todo:
        s = todo.pop()
        if s in tabs:
            continue
        tabs.add(s)
        refs = [w[0] for w in sp_tables.CODE[s][3] if isinstance(w, tuple)] if s in sp_tables.CODE             else [r[1] for r in sp_tables.ELF[s][4]]
        for t in refs:
            if t in defined or t in HOST_DEFINED or t == "_g_ps2_spr":
                continue
            need.setdefault(t, set()).add("sp_tables")
            if t in sp_tables.CODE or t in sp_tables.ELF:
                todo.append(t)
    for s in tabs:
        need.pop(s, None)

    from gen_headers import src_rel
    statics = {f["name"]: src_rel(f["src"]) for f in protofix.load_functions(os.path.join(ROOT, "symbols")) if f["static"]}
    fstubs, dstubs, external = [], collections.defaultdict(list), []
    for s in sorted(need):
        if s in data:
            dstubs[data[s][0]].append(s)
            continue
        m = MISSING.match(s)
        if m:
            ident = s[m.end():m.end() + int(m.group(1))]
            name, mrel = ident.split("__missing__")
            fstubs.append((s, name, unmangle_rel(mrel), True))
        elif s.startswith("_") and s[1:] in funcs:
            fstubs.append((s, s[1:], funcs[s[1:]], False))
        elif "sp_tables" in need[s] and s[1:] in statics:   # a static function of a file not native yet
            fstubs.append((s, s[1:], statics[s[1:]], False))
        else:
            external.append(s)   # C runtime (memcpy, sinf, ...): the toolchain resolves these

    # function stubs
    L = ["/* Generated by scripts/sp_missing.py: functions the decompiled code calls that are not decompiled yet. */",
         '#include "sp_missing.h"', "", "static const SpMissing g_missing[] = {"]
    L += [f'    {{"{n}", "{mod}"}},' for _, n, mod, _ in fstubs] + ["};", ""]
    for i, (label, n, mod, st) in enumerate(fstubs):
        L.append(f'extern "C" void sp_stub_{i}(void) __asm__("{label}");')
        L.append(f"void sp_stub_{i}(void) {{ sp_missing(&g_missing[{i}]); }}")
    open(os.path.join(out, "stub_funcs.cpp"), "w", newline="\n").write("\n".join(L) + "\n")

    # game data tables loaded from the user's disc at launch (storage + load table)
    want = sorted(s for syms in dstubs.values() for s in syms if s in ELF_DATA)
    want += sorted(s for s in tabs if s in sp_tables.ELF)
    fromelf = set(elf_data_unit(out, data, want))
    tables_unit(out, sorted(s for s in tabs if s in sp_tables.CODE))
    ovlreg_unit(out)
    for inc in list(dstubs):
        dstubs[inc] = [s for s in dstubs[inc] if s not in fromelf]
        if not dstubs[inc]:
            del dstubs[inc]

    # data stubs declared with an unknown bound (`T x[0]`, DWARF had no count): a zero-size definition lets the
    # next stub overlap it (s102: STAGE_ModelNum[0] writes clobbered ScrMsg / ScrTopP / Sm -> crash at the sortie
    # load). They get byte storage up to the next known PS2 symbol instead, in their own unit (the header's [0]
    # type would conflict with a sized definition; the linker only sees the label).
    addrs = sorted({v[2] for v in data.values()})
    zsize = []
    for inc in list(dstubs):
        for s in [s for s in dstubs[inc] if re.search(r"\[0\]", data[s][1])]:
            a = data[s][2]
            nxt = next((x for x in addrs if x > a), a + 16)
            zsize.append((s, a, nxt - a))
    zs = {z[0] for z in zsize}   # kept in dstubs for the report, skipped by the per-header units
    stubbed = {s for v in dstubs.values() for s in v}
    contig = []
    for grp in CONTIG:
        if all(s in stubbed and data[s][2] < OVERLAY_AREA for s in grp):
            last = data[grp[-1]][2]
            end = next((x for x in addrs if x > last), last + 16)
            contig.append((grp, data[grp[0]][2], end - data[grp[0]][2]))
            zs |= set(grp)
    L = ["/* Generated by scripts/sp_missing.py: unknown-bound game data stubs (zeroed), sized to the gap to the next",
         " * known PS2 symbol; overrun groups (CONTIG) as one block in PS2 order. */", 'extern "C" {']
    for grp, a0, n in contig:
        L.append(f'alignas(16) unsigned char sp_ct_{grp[0][1:]}[{n:#x}] __asm__("{grp[0]}") = {{}};   /* {a0:#x} */')
        for s in grp[1:]:
            L.append(f'__asm__(".globl {s}\\n.set {s}, {grp[0]}+{data[s][2] - a0:#x}");   /* {data[s][2]:#x} */')
    cur = "main"
    for s, a, n in sorted(zsize, key=lambda z: (z[1] >= OVERLAY_AREA, data[z[0]][3], z[1])):
        g = data[s][3] if a >= OVERLAY_AREA else "main"
        if g != cur:
            cur = g
            L.append(f'#pragma clang section data=".data$ovl_{cur}_m" bss=".bss$ovl_{cur}_m"')
        L.append(f'alignas(16) unsigned char sp_zs_{s[1:]}[{n:#x}] __asm__("{s}") = {{}};   /* {a:#x} */')
    L.append("}")
    open(os.path.join(out, "stub_data_zsize.cpp"), "w", newline="\n").write("\n".join(L) + "\n")

    # data stubs, one unit per header (local headers reuse C names across files)
    dbytes = 0
    for n, (inc, syms) in enumerate(sorted((i, [s for s in v if s not in zs]) for i, v in dstubs.items())):
        if not syms:
            continue
        L = ["/* Generated by scripts/sp_missing.py: game data owned by files that are not decompiled yet (zeroed). */",
             f'#include "{inc}"', 'extern "C" {']
        # main-address data first, then the overlay groups (port/platform/ovlreg; MW small data of overlay files sits
        # at main addresses and stays out of the groups)
        group = {s: data[s][3] if data[s][2] >= OVERLAY_AREA else "main" for s in syms}
        cur = "main"
        for s in sorted(syms, key=lambda s: (group[s] != "main", group[s])):
            if group[s] != cur:
                cur = group[s]
                L.append(f'#pragma clang section data=".data$ovl_{cur}_m" bss=".bss$ovl_{cur}_m"')
            text = data[s][1]
            al = HEAP_ALIGN.get(s.lstrip("_"))
            if al:   # backing array + the symbol at the PS2 address's phase (text = "char NAME[N]")
                mm = re.fullmatch(r"(?:unsigned )?char %s\[(\d+)\]" % re.escape(s.lstrip("_")), text.strip())
                if not mm:
                    sys.exit(f"sp_missing: HEAP_ALIGN {s}: unexpected declaration {text!r}")
                pad = data[s][2] % al
                L.append(f'alignas({al}) unsigned char sp_heap_{s[1:]}[{pad:#x} + {mm.group(1)}] __asm__("_sp_heap_{s[1:]}") = {{}};')
                L.append(f'__asm__(".globl {s}\\n.set {s}, _sp_heap_{s[1:]}+{pad:#x}");   /* {data[s][2]:#x} % {al:#x} */')
            else:
                L.append(f"{text} = {{}};")
        L.append("}")
        open(os.path.join(out, f"stub_data_{n:03d}.cpp"), "w", newline="\n").write("\n".join(L) + "\n")

    # overlay globals a main file defines (PS2 address in the overlay area, but the file's prelude has no overlay
    # group): Overlay_Load would not reset them. The other direction cannot happen: an overlay file's main-address
    # globals (MW small data) are declared into plain .data by its sp prelude (gen_bridge.py main_data_decls).
    oo = object_overlays()
    wrong = sorted(f"{s.lstrip('_')} ({o[:-2]}, {data[s][2]:#x})" for s, o in DATA_DEFS.items()
                   if s in data and oo.get(o) == "main" and data[s][2] >= OVERLAY_AREA)

    # report
    sc = scope()
    nat = natives()
    per = collections.defaultdict(lambda: [0, 0])
    for mod, key, name in sc:
        per[top(mod)][1] += 1
        # SDK natives (lib/sdk/, newlib ones renamed ps2_*) are registered by runtime/bridge_sdk.c, not gen_bridge.py
        if key in nat or mod == "sdk" and ({"_" + name, "_ps2_" + name.lstrip("_")} & defined):
            per[top(mod)][0] += 1
    miss = collections.defaultdict(list)
    for _, n, mod, _ in fstubs:
        miss[mod].append(n)
    scope_names = {n for _, _, n in sc}
    R = ["# Source port: missing functions", "",
         f"Versus scope (functions executed in Versus): **{sum(v[0] for v in per.values())} / {len(sc)} native**. "
         f"The source-port link needs **{len(fstubs)} functions** that are still missing "
         f"({sum(1 for f in fstubs if f[1] in scope_names)} of them run in Versus) and "
         f"**{sum(len(v) for v in dstubs.values())} game data objects** (zero-filled stand-ins for now)"
         + (f"; {len(fromelf)} loaded from the disc's ELF at launch ({', '.join(s[1:] for s in sorted(fromelf))})"
            if fromelf else "") + ".", "",
         "## Versus progress by module", "", "| module | native | in scope |", "|---|---:|---:|"]
    for mod, (a, b) in sorted(per.items(), key=lambda kv: -kv[1][1]):
        R.append(f"| {mod} | {a} | {b} |")
    R += ["", "## Called by native code but missing (by source file)", "",
          "`*` = not executed in Versus (referenced only).", ""]
    for mod in sorted(miss):
        names = ", ".join(n + ("" if n in scope_names else "*") for n in sorted(miss[mod]))
        R.append(f"* **{mod}** ({len(miss[mod])}): {names}")
    render = render_missing(fstubs)
    R += ["", f"## Render: builders / SDK render functions not native yet ({len(render)})", "",
          "src/gfx/ modules, functions named and the SDK GS / DMA calls; the render module "
          "(port/render) itself is linked (null backend until phase 3).", "",
          ", ".join(f"{n} ({mod})" + ("" if n in scope_names else "*") for n, mod in render)]
    ranges = initialized_ranges()
    if ranges:
        init = sorted(f"{decl_name(LABEL.sub('', data[s][1]))} ({data[s][0][len('acnb/'):]})"
                      for syms in dstubs.values() for s in syms
                      # main-ELF sdata of an overlay source file (function statics, gp data below the overlay
                      # area: mfont's SJIS `prim` words) is in the main image (was missed before s98)
                      if any(o == ("main" if data[s][2] < OVERLAY_AREA else data[s][3]) and lo <= data[s][2] < hi
                             for o, lo, hi in ranges))
        R += ["", f"## Zero-filled game data that the original initializes ({len(init)} of "
              f"{sum(len(v) for v in dstubs.values())})", "",
              "These need their real initial values (decompiled as C++ initializers) before the code that reads "
              "them can run correctly; the rest is .bss and zero is right.", "", ", ".join(init)]
    R += ["", f"## Overlay globals outside their overlay group ({len(wrong)})", "",
          "Defined in a main file, so Overlay_Load (port/platform/ovlreg) does not reset them.", "",
          ", ".join(wrong)]
    R += ["", f"## Resolved by the C runtime ({len(external)})", "", ", ".join(s.lstrip("_") for s in external), ""]
    open(report, "w", newline="\n").write("\n".join(R))
    print(f"sp_missing: render category {len(render)} functions")
    if wrong:
        print(f"sp_missing: {len(wrong)} overlay globals outside their overlay group (see the report)")
    print(f"sp_missing: {len(fstubs)} function stubs, {sum(len(v) for v in dstubs.values())} data stubs, "
          f"{len(external)} left to the C runtime, {len(tabs)} tables from sp_tables "
          f"({sum(1 for s in tabs if s in sp_tables.CODE)} in code, {sum(1 for s in tabs if s in sp_tables.ELF)} "
          f"from the disc) -> {report}")


if __name__ == "__main__":
    main()
