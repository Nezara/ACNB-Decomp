def render_missing(fstubs):
    """missing functions that build or kick render packets: (name, module), sorted by module"""
    txt = ""
    named = {t for t in re.findall(r"[A-Za-z_][A-Za-z0-9_]+", txt) if len(t) >= 5 and ("_" in t or t != t.lower())}
    sdk = re.compile(r"^(sce(Gs|Dma|Vif|Gif)|FlushCache$)")
    out = {(n, mod) for _, n, mod, _ in fstubs
           if mod.startswith("src/gfx/") or n in named or mod == "sdk" and sdk.match(n)}
    return sorted(out, key=lambda x: (x[1], x[0]))


