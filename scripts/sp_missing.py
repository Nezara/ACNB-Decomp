        d = open(os.path.join(ext, "SLUS_212.00"), "rb").read(0x100)
        phoff = struct.unpack_from("<I", d, 0x1c)[0]
        _, _, va, _, filesz = struct.unpack_from("<5I", d, phoff)
        r = [("main", va, va + filesz)]
