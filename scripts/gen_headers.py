"""Generate the port's C headers from the DWARF dumps (symbols/*.json).

    python gen_headers.py            -> port/include/acnb/types.h, globals.h, funcs.h
                                        port/gen/globals_abs.s

Targets i686 (pointers 4 bytes, PS2 struct layout). Every aggregate gets
_Static_asserts on its size and member offsets so layout drift fails the build.
Structs whose natural i686 layout differs from the PS2 one are emitted packed with
explicit padding (see FIXUP output).
"""
import json
import os
import re

import protofix

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYM = os.path.join(ROOT, "symbols")
OUT_INC = os.path.join(ROOT, "port", "include", "acnb")
OUT_GEN = os.path.join(ROOT, "port", "gen")

FUND_C = {"long double": "double", "bool": "mw_bool", "void *": "void *"}
ALIGN = {"char": 1, "signed char": 1, "unsigned char": 1, "short": 2, "unsigned short": 2,
         "int": 4, "unsigned int": 4, "long long": 8, "unsigned long long": 8, "float": 4,
         "double": 8, "long double": 8, "void *": 4, "bool": 1, "u_long128": 16, "void": 1}
SIZE = dict(ALIGN, **{"long double": 8, "void": 0})
# Decompiled code is C++: DWARF names that are C++ keywords get a trailing underscore (only parameters and one
# static global named "this" occur; linkage names are kept through asm labels).
CPP_KW = set("""alignas alignof and and_eq asm bitand bitor bool catch char8_t char16_t char32_t class compl concept
consteval constexpr constinit const_cast co_await co_return co_yield decltype delete dynamic_cast explicit export false
friend mutable namespace new noexcept not not_eq nullptr operator or or_eq private protected public reinterpret_cast
requires static_assert static_cast template this thread_local throw true try typeid typename using virtual wchar_t xor
xor_eq""".split())


def cid(name):
    return name + "_" if name in CPP_KW else name


def cdecl(s, name=""):
    k = s[0]
    if k == "fund":
        base = FUND_C.get(s[1], s[1])
        if base == "void *":
            return f"void *{name}".rstrip()
        return f"{base} {name}".rstrip()
    if k in ("struct", "union"):
        return f"{k} {s[1]} {name}".rstrip()
    if k == "enum":
        return f"{s[1]} {name}".rstrip()
    if k in ("const", "volatile"):
        inner = s[1]
        if inner[0] == "ptr":
            return cdecl(inner, f"{k} {name}".rstrip()).replace("* " + k, "*" + k)
        return f"{k} {cdecl(inner, name)}"
    if k == "ptr":
        inner = s[1]
        if inner[0] in ("array", "func"):
            return cdecl(inner, f"(*{name})")
        return cdecl(inner, f"*{name}")
    if k == "array":
        return cdecl(s[2], name + "".join(f"[{max(d, 0)}]" for d in s[1]))
    if k == "func":
        ps = ", ".join(cdecl(p) for p in s[2]) or "void"
        return cdecl(s[1], f"{name}({ps})")
    return f"int {name}"


class Layout:
    """PS2 (MW) natural layout calculator, used to decide which structs need packing."""

    def __init__(self, types):
        self.types = types

    def size_align(self, s):
        k = s[0]
        if k == "fund":
            return SIZE.get(s[1], 4), ALIGN.get(s[1], 4)
        if k == "ptr":
            return 4, 4
        if k in ("const", "volatile"):
            return self.size_align(s[1])
        if k == "array":
            n = 1
            for d in s[1]:
                n *= max(d, 0)
            sz, al = self.size_align(s[2])
            return sz * n, al
        if k == "enum":
            t = self.types.get(s[1])
            sz = t["size"] if t else 4
            return sz, sz
        if k in ("struct", "union"):
            t = self.types.get(s[1])
            if not t:
                return 0, 1
            al = 1
            for m in t.get("members", []):
                al = max(al, self.size_align(m["type"])[1])
            return t["size"], al
        return 4, 4


def main():
    types = json.load(open(os.path.join(SYM, "types.json")))
    lay = Layout(types)
    os.makedirs(OUT_INC, exist_ok=True)
    os.makedirs(OUT_GEN, exist_ok=True)

    L = ["/* Generated by scripts/gen_headers.py from SLUS_212.00 DWARF. Do not edit. */",
         "#pragma once", "#include <stddef.h>", "",
         "typedef struct { unsigned int w[4]; } __attribute__((aligned(16))) u_long128;",
         "typedef unsigned char mw_bool;", ""]
    for n, t in types.items():
        if t["kind"] != "enum":
            L.append(f"typedef {t['kind']} {n} {n};")
    L.append("")
    intty = {1: "signed char", 2: "short", 4: "int", 8: "long long"}
    for n, t in types.items():
        if t["kind"] == "enum":
            L.append(f"typedef {intty.get(t['size'], 'int')} {n}; /* enum */")
            L.append(f"enum {n}__values {{")
            L += [f"    {k} = {v}," for k, v in t["values"]]
            L.append("};")
    L.append("")

    done, emitting = set(), set()
    asserts = []
    packed = []

    def deps(s, acc):
        if s[0] in ("struct", "union"):
            acc.add(s[1])
        elif s[0] == "array":
            deps(s[2], acc)
        elif s[0] in ("const", "volatile"):
            deps(s[1], acc)

    def emit(n):
        if n in done or n in emitting or n not in types:
            return
        emitting.add(n)
        t = types[n]
        acc = set()
        for m in t.get("members", []):
            deps(m["type"], acc)
        for d in sorted(acc):
            emit(d)
        emitting.discard(n)
        done.add(n)
        if t["kind"] == "enum":
            return
        _, al = lay.size_align([t["kind"], n])
        while al > 1 and t["size"] % al:
            al //= 2
        body = emit_members(n, t, items_of(t))
        L.append(f"{t['kind']} __attribute__((packed, aligned({al}))) {n} {{ /* size {t['size']:#x} */")
        L.extend("    " + b for b in body)
        L.append("};")
        L.append("")
        for m in t["members"]:
            if m["name"] and "bit_size" not in m:
                asserts.append(f"_Static_assert(offsetof({n}, {m['name']}) == {m['offset']:#x}, \"{n}.{m['name']}\");")
        if t["size"]:
            asserts.append(f"_Static_assert(sizeof({n}) == {t['size']:#x}, \"sizeof {n}\");")

    # ---- explicit layout: items -> union regions -> packed lines
    def items_of(t):
        """Members as layout items: ('m', member, off, end) or ('bf', [members], off, end, unit)."""
        out, i, ms = [], 0, t["members"]
        while i < len(ms):
            m = ms[i]
            if "bit_size" not in m:
                sz = lay.size_align(m["type"])[0]
                out.append(("m", m, m["offset"], m["offset"] + sz))
                i += 1
                continue
            grp, hi = [m], m["bit_offset"] + m["bit_size"]
            j = i + 1
            while (j < len(ms) and "bit_size" in ms[j] and ms[j]["offset"] == m["offset"]
                   and ms[j]["bit_offset"] >= hi):
                grp.append(ms[j])
                hi = ms[j]["bit_offset"] + ms[j]["bit_size"]
                j += 1
            need = (hi + 7) // 8
            unit = next(u for u in (1, 2, 4, 8) if u >= need)  # MW shrinks units; pad bits explicitly
            out.append(("bf", grp, m["offset"], m["offset"] + unit, unit))
            i = j
        return out

    counter = [0]

    def pad(nbytes):
        counter[0] += 1
        return f"unsigned char _pad{counter[0]}[{nbytes:#x}];"

    def item_lines(it):
        if it[0] == "m":
            m = it[1]
            nm = m["name"] or f"_anon{counter[0]}"
            counter[0] += 1
            return [f"{cdecl(m['type'], nm)}; /* {m['offset']:#x} */"]
        grp, unit = it[1], it[4]
        signed = not grp[0]["type"][1].startswith("unsigned")
        ty = {1: "char", 2: "short", 4: "int", 8: "long long"}[unit]
        ty = ("signed " if signed else "unsigned ") + ty
        lines, bit = [], 0
        for b in grp:
            if b["bit_offset"] > bit:
                lines.append(f"unsigned {ty.split(' ', 1)[1]} : {b['bit_offset'] - bit};")
            lines.append(f"{ty} {b['name']} : {b['bit_size']}; /* {b['offset']:#x}.{b['bit_offset']} */")
            bit = b["bit_offset"] + b["bit_size"]
        if bit < unit * 8:
            lines.append(f"unsigned {ty.split(' ', 1)[1]} : {unit * 8 - bit};")
        return lines

    def seq_lines(items, base):
        lines, pos = [], base
        for it in items:
            if it[2] > pos:
                lines.append(pad(it[2] - pos))
            lines += item_lines(it)
            pos = max(pos, it[3])
        return lines, pos

    def emit_members(n, t, items):
        lines, pos, k = [], 0, 0
        # suffix minimum of item offsets: a region (possible flattened union) may only end
        # where every later item starts at/after everything emitted so far
        sufmin = [0] * (len(items) + 1)
        sufmin[-1] = 1 << 40
        for i in range(len(items) - 1, -1, -1):
            sufmin[i] = min(items[i][2], sufmin[i + 1])
        while k < len(items):
            arms, start, end = [[items[k]]], items[k][2], items[k][3]
            k += 1
            while k < len(items) and sufmin[k] < end:
                it = items[k]
                if it[2] < arms[-1][-1][3]:
                    arms.append([it])
                else:
                    arms[-1].append(it)
                end = max(end, it[3])
                k += 1
            if start > pos:
                lines.append(pad(start - pos))
            if len(arms) == 1:
                body, _ = seq_lines(arms[0], start)
                lines += body
            else:
                lines.append("union __attribute__((packed)) {")
                for arm in arms:
                    body, _ = seq_lines(arm, start)
                    if len(body) == 1 and not arm[0][2] > start and arm[0][0] == "m":
                        lines.append("    " + body[0])
                    else:
                        lines.append("    struct __attribute__((packed)) {")
                        lines += ["        " + b for b in body]
                        lines.append("    };")
                lines.append("};")
            pos = max(pos, end)
        if t["size"] > pos:
            lines.append(pad(t["size"] - pos))
        if t["kind"] == "union" and len(lines) > 1:
            lines = ["struct __attribute__((packed)) {"] + ["    " + b for b in lines] + ["};"]
        return lines

    for n in types:
        emit(n)
    L.append("#ifdef ACNB_LAYOUT_ASSERTS")
    L += asserts
    L.append("#endif")
    open(os.path.join(OUT_INC, "types.h"), "w").write("\n".join(L) + "\n")
    print("types.h: %d types, %d packed, %d asserts" % (len(types), len(packed), len(asserts)))
    gen_symbols()


def src_rel(src):
    """Original source path -> port-relative stem, e.g. src/ac/acact, lib/fslibmpg2_dd/mpg."""
    s = src.replace("\\", "/")
    stem = s.rsplit(".", 1)[0]
    if "/ac/src/" in s:
        return "src/" + stem.split("/ac/src/", 1)[1]
    if "/ac/lib/" in s:
        return "lib/" + stem.split("/ac/lib/", 1)[1].replace("fs/lib/", "fs/")
    if "/ext/lib/" in s:
        rest = stem.split("/ext/lib/", 1)[1].split("/")
        return "lib/%s/%s" % (rest[0], rest[-1])
    return "misc/" + stem.rsplit("/", 1)[-1]


EXTERN_C_BEGIN = '#ifdef __cplusplus\nextern "C" {\n#endif'
EXTERN_C_END = '#ifdef __cplusplus\n}\n#endif'


def mangle(*parts):
    return "__".join(re.sub(r"[^A-Za-z0-9_]", "_", p) for p in parts)


def proto(f, name=None):
    ps = ", ".join(cdecl(p["type"], cid(p["name"] or "")) for p in f["params"]) or "void"
    return cdecl(f["ret"], f"{name or f['name']}({ps})")


def gen_symbols():
    gl = json.load(open(os.path.join(SYM, "globals.json")))
    fs = protofix.load_functions(SYM)
    asm = ["# Generated by scripts/gen_headers.py: globals at their original PS2 addresses.", ""]
    hdr = ["/* Generated by scripts/gen_headers.py. Do not edit. */", "#pragma once",
           '#include "acnb/types.h"', "",
           "/* source port: globals are host objects; the ones at a 16-aligned PS2 address keep that alignment (lq / sq",
           " * helpers round down, src/lib/func.cpp). The hybrid binds them to their PS2 addresses (symbols_abs.s). */",
           "#ifdef ACNB_SOURCEPORT", "#define PS2_GALIGN __attribute__((aligned(16)))", "#else", "#define PS2_GALIGN",
           "#endif", "", EXTERN_C_BEGIN]
    per_file = {}
    seen = set()
    public_names = {g["name"] for g in gl if not g["static"] and g["addr"]}
    nstat = 0
    for g in sorted(gl, key=lambda g: g["addr"]):
        if not g["addr"]:
            continue
        rel = src_rel(g["src"])
        if not g["static"]:
            if g["name"] in seen:
                continue
            seen.add(g["name"])
            lab = f' __asm__("_{g["name"]}")' if cid(g["name"]) != g["name"] else ""
            al = " PS2_GALIGN" if g["addr"] % 16 == 0 else ""
            hdr.append(f"extern {cdecl(g['type'], cid(g['name']))}{lab}{al}; /* {g['addr']:#010x} {g['overlay']} */")
            asm += [f".globl _{g['name']}", f".set _{g['name']}, {g['addr']:#x}"]
            continue
        nstat += 1
        if g["scope"]:
            cname = f"{g['scope']}__{g['name']}"
            label = mangle(g["name"], "F", g["scope"], rel)
        else:
            cname = cid(g["name"])
            label = mangle(g["name"], "S", rel)
        if cname in public_names:
            cname = mangle(g["name"], "S", rel.rsplit("/", 1)[-1])
        asm += [f".globl _{label}", f".set _{label}, {g['addr']:#x}"]
        per_file.setdefault(rel, []).append(
            f"extern {cdecl(g['type'], cname)} __asm__(\"_{label}\"){' PS2_GALIGN' if g['addr'] % 16 == 0 else ''};"
            f" /* {g['addr']:#010x} */")

    funcs = ["/* Generated by scripts/gen_headers.py. Do not edit. */", "#pragma once",
             '#include "acnb/types.h"', "", EXTERN_C_BEGIN]
    fseen = set()
    for f in sorted(fs, key=lambda f: f["addr"]):
        rel = src_rel(f["src"])
        if f["static"]:
            per_file.setdefault(rel, []).append(f"static {proto(f)}; /* {f['addr']:#010x} */")
        elif f["name"] not in fseen:
            fseen.add(f["name"])
            funcs.append(f"{proto(f)}; /* {f['addr']:#010x} {rel} */")

    open(os.path.join(OUT_INC, "globals.h"), "w").write("\n".join(hdr + [EXTERN_C_END]) + "\n")
    open(os.path.join(OUT_INC, "funcs.h"), "w").write("\n".join(funcs + [EXTERN_C_END]) + "\n")
    open(os.path.join(OUT_GEN, "symbols_abs.s"), "w").write("\n".join(asm) + "\n")
    for rel, lines in per_file.items():
        p = os.path.join(OUT_INC, "local", rel + ".h")
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write("\n".join(["/* Generated by scripts/gen_headers.py: file-local statics. */",
                                      "#pragma once", '#include "acnb/globals.h"',
                                      '#include "acnb/funcs.h"', "", EXTERN_C_BEGIN] + lines + [EXTERN_C_END]) + "\n")
    print("globals.h: %d public, %d statics; funcs.h: %d; %d per-file headers"
          % (len(seen), nstat, len(fseen), len(per_file)))


if __name__ == "__main__":
    main()
