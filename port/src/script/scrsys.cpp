/* src/script/scrsys.cpp — "system" command group of the stage scripts (kind 100..199: fades, HUD, conditions).
 * SCRSYS_CallScript (jump table trampoline) dispatches through the original table (gcall); CondChange and
 * GaugeOnOff run in Versus, MissionEnd in garage3. */
#include "acnb/ps2fp.h"

/* Cond_SetNowCond's id: MWCC's float -> unsigned conversion. */
static unsigned int scrsys_ftou(float f)
{
    if (2147483648.0f <= f) return (unsigned int)ps2_ftoi(f - 2147483648.0f) | 0x80000000u;
    return (unsigned int)ps2_ftoi(f);
}

static void scrsys_cond_mode(__scr_fifo_st *ss, int m)
{
    int intp = ps2_ftoi(ps2_u2f(ss->arg[3].val));
    int in = ps2_ftoi(ps2_u2f(ss->arg[0].val));
    int out = ps2_ftoi(ps2_u2f(ss->arg[1].val));
    int frame = ps2_ftoi(ps2_u2f(ss->arg[2].val));
    Cond_Set(m, intp, in, out, frame);
    Cond_SetNowCond((unsigned char)m, (unsigned char)scrsys_ftou(ps2_u2f(ss->arg[1].val)));
}

/* Kind 116: interpolates element arg4 (0 = all four, 1..4 = one) from condition arg0 to arg1 over arg2 frames
 * (type arg3). Quirk: any other arg4 returns without Cond_Run and without finishing the command (the script hangs). */
static void __scrsys_CondChange(__scr_fifo_st *ss)
{
    PS2_FRAME(0x30);
    int which = ps2_ftoi(ps2_u2f(ss->arg[4].val));
    if (which == 0) {
        for (int m = 0; m < 4; m++) scrsys_cond_mode(ss, m);
    } else if (which >= 1 && which <= 4) {
        scrsys_cond_mode(ss, which - 1);
    } else {
        return;
    }
    Cond_Run(0, 1);
    ss->kind = 0;
}

/* Kind 101: HUD gauge on / off; on also re-enables the NPCs and resets the view mode, off stops them (movie play). */
static void __scrsys_GaugeOnOff(__scr_fifo_st *ss)
{
    PS2_FRAME(0x20);
    MyI.gauge = (char)ps2_ftoi(ps2_u2f(ss->arg[0].val));
    if (MyI.gauge) {
        MyI.mov_play = 0;
        DF_EVT_SetNPCFlag(1, 1, 1, 1);   /* the asm also passes -1 in t0 (unused 5th argument) */
        ViewMode_CheckAll(1);
    } else {
        MyI.mov_play = 1;
        DF_EVT_SetNPCFlag(0, 0, 0, 0);   /* t0 = -1 as above */
    }
    ss->kind = 0;
}

/* Kind 115: ends the mission with result arg0 (1 / 6 failure, 3 / 5 / 8 / 9 success, 7 statMission 5 + success;
 * 5 and 6 also set MyI.message; 0, 2, 4 and anything else only finish the command) unless it already ended.
 * Quirk: while AC 0 is dead the command is not finished (it re-runs every frame). */
static void __scrsys_MissionEnd(__scr_fifo_st *ss)
{
    PS2_FRAME(0x30);
    int n = ps2_ftoi(ps2_u2f(ss->arg[0].val));
    if (!AcCtrl_IsAlive(0)) return;
    StSortieWork *w = g_sortie.pwork;
    if (w->statMission != 0) {
        ss->kind = 0;
        return;
    }
    switch ((unsigned int)n) {   /* jump table OLSORTIE 0x1e6de10 */
    case 3: case 8: case 9:
        w->statMission = 3;
        g_sortie.pwork->isSuccess = 1;
        break;
    case 5:
        w->statMission = 3;
        g_sortie.pwork->isSuccess = 1;
        MyI.message = 1;
        break;
    case 1:
        w->statMission = 1;
        g_sortie.pwork->isSuccess = 0;
        break;
    case 6:
        w->statMission = 1;
        g_sortie.pwork->isSuccess = 0;
        MyI.message = 1;
        break;
    case 7:
        w->statMission = 5;
        g_sortie.pwork->isSuccess = 1;
        break;
    default:
        break;
    }
    ss->kind = 0;
}

/* The group's dispatcher: handler s_pJobSystemScrFunc[type] (a tail jump in the original; type is not
 * range-checked). */
void SCRSYS_CallScript(unsigned char type, __scr_fifo_st *ss)
{
    gcall(s_pJobSystemScrFunc[type], ss);
}

