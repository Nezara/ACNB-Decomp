/* src/script/scrchara.cpp (OLSORTIE) - "chara" command group of the stage scripts (kind 400..499: enemy / character
 * commands). Versus reaches only the dispatcher and kind 409 (all characters on / off, battle_marine); the enemy
 * handlers stay interpreted. */
#include "acnb/ps2fp.h"

/* Kind 409: arg0 (float) = on / off for every character. */
static void __srcchara_EneAllOnOff(__scr_fifo_st *ss)
{
    PS2_FRAME(0x20);
    EVMNG_AllChrOnOff(ps2_ftoi(ps2_u2f(ss->arg[0].val)));
    ss->kind = 0;
}

/* Kind 426: arg0 (float) = think on / off for every enemy (garage3). */
static void __srcchara_AllEneThinkOnOff(__scr_fifo_st *ss)
{
    PS2_FRAME(0x20);
    Enemy_AllEnemyThinkOnOff(ps2_ftoi(ps2_u2f(ss->arg[0].val)));
    ss->kind = 0;
}

/* The group's dispatcher (s_pJobExecFunc[4]): handler s_pJobCharaScrFunc[id] (a tail jump in the original; the table
 * has 34 entries, a larger id would run into the next group's table - never happens). */
void SCRCHARA_CallScript(unsigned char type, __scr_fifo_st *ss)
{
    gcall(s_pJobCharaScrFunc[type], ss);
}

