/* src/script/scrsnd.cpp — "sound" command group of the stage scripts (kind 500..599). SCRSND_CallScript (jump table
 * trampoline) dispatches through the original table (gcall); only __scrsnd_VsMapBgmRandPlayBack, __scrsnd_ADSRandPlayBack (battle_marine) and __scrsnd_ADSPlayBack (sandbox arena) run
 * in Versus. */
#include "acnb/ps2fp.h"

/* Kind 503: stage BGM start - a random stage BGM in sortie mode 4, else BGM arg0; looped. */
static void __scrsnd_VsMapBgmRandPlayBack(__scr_fifo_st *ss)
{
    PS2_FRAME(0x20);
    if (g_sortie.pconstant->modeSortie == 4) Snd_PlayStageBgmRandom(MyI.bgm_random, 1);
    else Snd_PlayStageBgm(ps2_ftoi(ps2_u2f(ss->arg[0].val)), 1);
    ss->kind = 0;
}

/* Kind 5xx: a random stage BGM, then wait arg0 (float) frames and finish (clear the fifo work area and the kind).
 * Quirk (kept): wkL[0] is never set, so the BGM is restarted on every call until the wait runs out (wkL[1] is reset
 * each call: only a wait <= 1 finishes; battle_marine uses that). */
static void __scrsnd_ADSRandPlayBack(__scr_fifo_st *ss)
{
    PS2_FRAME(0x20);
    if (ss->wkL[0] == 0) {
        Snd_PlayStageBgmRandom(MyI.bgm_random, 1);
        ss->wkL[1] = ps2_ftoi(ps2_u2f(ss->arg[0].val));
    }
    if (--ss->wkL[1] > 0) return;
    ss->wkL[3] = 0;
    ss->wkL[2] = 0;
    ss->wkL[1] = 0;
    ss->wkL[0] = 0;
    ss->wkL[6] = 0;
    ss->wkL[5] = 0;
    ss->wkL[4] = 0;
    ss->wkF[3] = 0.0f;
    ss->wkF[2] = 0.0f;
    ss->wkF[1] = 0.0f;
    ss->wkF[0] = 0.0f;
    ss->wkF[6] = 0.0f;
    ss->wkF[5] = 0.0f;
    ss->wkF[4] = 0.0f;
    ss->kind = 0;
}

/* Kind 513: stage BGM arg0, or arg1 when the sortie uses the arranged BGM and arg1 is set; looped. Only kind is
 * cleared. The isArrangeBgm arm is asm-only (REV). */
static void __scrsnd_ADSPlayBack(__scr_fifo_st *ss)
{
    PS2_FRAME(0x20);
    int adsid1 = ps2_ftoi(ps2_u2f(ss->arg[0].val));
    int adsid2 = ps2_ftoi(ps2_u2f(ss->arg[1].val));
    if (g_sortie.pconstant->isArrangeBgm != 0 && adsid2 != 0) Snd_PlayStageBgm(adsid2, 1);
    else Snd_PlayStageBgm(adsid1, 1);
    ss->kind = 0;
}

/* The group's dispatcher: handler s_pJobSndScrFunc[type] (a tail jump in the original; type is not range-checked). */
void SCRSND_CallScript(unsigned char type, __scr_fifo_st *ss)
{
    gcall(s_pJobSndScrFunc[type], ss);
}

