/* src/script/scrac.cpp — "AC" command group of the stage scripts (kind 200..299). SCRAC_CallScript (a 40-byte jump
 * table trampoline) dispatches through the original table (gcall), so interpreted handlers stay reachable.
 * __srcac_SetAcCtrlOnOff runs in Versus, AcDeadMissonStop / AcZeroVelocity in garage3; the others stay interpreted. */
#include "acnb/ps2fp.h"

/* Kind 201: arg0 = event id of an AC, arg1 = control on / off. Off also sets the player's padoff when it is AC 0.
 * Quirk: the AC index comes from the script unchecked. */
static void __srcac_SetAcCtrlOnOff(__scr_fifo_st *ss)
{
    PS2_FRAME(0x50);
    __evmng_event_id_st *ev = EVMNG_GetEventID(ps2_ftoi(ps2_u2f(ss->arg[0].val)));
    AcPlayerSt *acp = &g_ac[ev->id];
    int on = ps2_ftoi(ps2_u2f(ss->arg[1].val));
    AC_ClearKeybuff(acp);
    if (on) {
        acp->stat &= 0xbfff;
        if (ev->id == 0) MyI.padoff = 0;
    } else {
        acp->stat |= 0x4000;
        if (ev->id == 0) MyI.padoff = 1;
    }
    AC_SetControl(acp, on);
    acp->comthinkoff = on == 0;
    ss->kind = 0;
}

/* Kind 227: MyI.deadstop = arg0 (MWCC's float -> unsigned conversion, stored as a byte). */
static void __srcac_AcDeadMissonStop(__scr_fifo_st *ss)
{
    float f = ps2_u2f(ss->arg[0].val);
    unsigned int u;
    if (2147483648.0f <= f) u = (unsigned int)ps2_ftoi(f - 2147483648.0f) | 0x80000000u;
    else u = (unsigned int)ps2_ftoi(f);
    MyI.deadstop = (unsigned char)u;
    ss->kind = 0;
}

/* Kind 219: puts the AC of event arg0 at its model's position (StModel + 0x10). Quirk: AC index unchecked. */
static void __srcac_AcZeroVelocity(__scr_fifo_st *ss)
{
    PS2_FRAME(0x20);
    __evmng_event_id_st *ev = EVMNG_GetEventID(ps2_ftoi(ps2_u2f(ss->arg[0].val)));
    AcPlayerSt *acp = &g_ac[ev->id];
    AC_SetPosition(acp, (float *)((char *)acp->mp + 0x10));
    ss->kind = 0;
}

/* The group's dispatcher: handler s_pJobAcScrFunc[type] (a tail jump in the original; type is not range-checked). */
void SCRAC_CallScript(unsigned char type, __scr_fifo_st *ss)
{
    gcall(s_pJobAcScrFunc[type], ss);
}

