/* src/ac/parts_noleg.cpp - ACs without legs (hover / floater type; whole file, OLSORTIE overlay). acnoleg_Control
 * keeps the AC hovering: within 50 of the ground (or the water surface) the fall speed is capped by a sine-eased
 * limit and the hover effect level is set; the nolegac_* functions are the leg-type action handlers (move / turn /
 * stop / fly up) reached through the interpreted action tables. */
#include "acnb/port.h"
#include "acnb/sdk.h"
#include "acnb/ps2fp.h"

static void nolegac_hovering(AcPlayerSt *acp)
{
    PS2_FRAME(0x20);
    if (acp->actno == 2 || acp->actno == 0x10) return;
    float h = acp->floor_high, w = acp->water_high;
    if (!(h <= w) && !(w <= acp->loc[1] - 0.01f)) h = w;
    float d = h - acp->loc[1];
    if (!(d <= 50.0f)) return;
    float s = acp->param.fall_maxspd * fsmath_SinVU0(1.5707964f * d / 50.0f);
    if (s < 0.0f) s = 0.0f;
    float vy = acp->velocity[1];
    if (s < vy) {
        float diff = vy - s;
        if (!(diff <= acp->param.gravity)) {
            acp->effectstat |= 2;
            acp->hover_effectlv = 2;
        }
        if (!(diff <= 0.5f)) diff = 0.5f;
        acp->velocity[1] = acp->velocity[1] - diff;
    }
    if (!(acp->effectstat & 2)) {
        acp->effectstat |= 0x4000;
        float vx2 = acp->velocity[0] * acp->velocity[0];
        float vz2 = acp->velocity[2] * acp->velocity[2];
        float speed = ps2_sqrt(vx2 + vz2);   /* mula.s / madd.s */
        acp->hover_effectlv = (speed <= 0.1f) ? 0 : 1;
    }
}

void acnoleg_Control(AcPlayerSt *acp)
{
    nolegac_hovering(acp);
}

static int nolegac_setact_fly_or_dash(AcPlayerSt *acp)
{
    PS2_FRAME(0x20);
    if (AcCtrl_IsCharging(acp)) return 0;
    if (AcUidev_IsMoving(acp->frdp->uidevp)) {
        AC_SetAction(acp, 5);
        return 1;
    }
    acp->velocity[1] = -acp->param.flyup_accel;
    AC_SetAction(acp, 8);
    return 1;
}

static int nolegac_setact_move(AcPlayerSt *acp)
{
    PS2_FRAME(0x10);
    AC_SetAction(acp, 3);
    return 1;
}

static int nolegac_act_flyup(AcPlayerSt *acp)
{
    PS2_FRAME(0x20);
    AcCtrl_BrakeXz(acp, acp->param.flymv_brk);
    acp->velocity[1] = -acp->param.flyup_accel;
    AC_SetAction(acp, 8);
    return 1;
}

/* while the leg animation blends in, the core / waist objects use the walk blend times */
static void nolegac_hokan_fix(AcPlayerSt *acp)
{
    ObjectSt *op = acp->op;
    if (op[2].hokanframe != op[2].hokantime) {
        op[3].hokantime = acp->param.hokanparamp->walk_core;
        acp->op[14].hokantime = acp->param.hokanparamp->walk_waist;
    }
}

static int nolegac_act_move(AcPlayerSt *acp, unsigned short dir)
{
    PS2_FRAME(0x50);
    AcAnim_ChangeAnim(acp, nolegac_act_move__dir2animid[dir], 0xb4, 1);
    nolegac_hokan_fix(acp);
    AcCtrl_TurnPad(acp, acp->param.turn_accel, acp->param.turn_maxspd);
    if (dir == 8) {
        AcCtrl_BrakeXz(acp, acp->param.flymv_brk);
    } else {
        float maxspd = acp->param.flymv_maxspd;
        float accel = acp->param.flymv_accel;
        if (AcUidev_IsAnalog(acp->frdp->uidevp)) {
            char alh = AcUidev_GetPadStickConf(acp->frdp->uidevp, 0);
            char alv = AcUidev_GetPadStickConf(acp->frdp->uidevp, 1);
            float r = AcUidev_ApplyAnalogLegRate(dir, alh, alv, 0.1f, NULL);
            accel = accel * r;
            maxspd = maxspd * r;
        }
        AcCtrl_Accel8Dir(acp, dir, accel, maxspd);
        acp->soundstat |= 1;
    }
    return 1;
}

static int nolegac_act_turn(AcPlayerSt *acp)
{
    PS2_FRAME(0x20);
    if (acp->actstep == 0) {
        acp->turnspd = 0.0f;
        acp->actstep++;
    }
    int animid = AcUidev_IsPadOnConf(acp->frdp->uidevp, 2) ? 0x21 : 0x22;
    AcAnim_ChangeAnim(acp, animid & 0xff, 0x78, 0);
    AcCtrl_TurnPad(acp, acp->param.turn_accel, acp->param.turn_maxspd);
    AcCtrl_BrakeXz(acp, acp->param.flymv_brk);
    acp->soundstat |= 2;
    return 1;
}

static int nolegac_act_stop(AcPlayerSt *acp)
{
    PS2_FRAME(0x20);
    AcAnim_ChangeAnim(acp, 0, 0x78, 1);
    nolegac_hokan_fix(acp);
    AcCtrl_BrakeXz(acp, acp->param.flymv_brk);
    return 1;
}

