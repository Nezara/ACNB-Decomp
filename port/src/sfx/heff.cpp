/* src/sfx/heff.cpp - hit effects (HitEffect[], HitEffectNum). Native so far: the after-pass dispatcher
 * DF_EFF2_HitEffectProcAfter, the empty DF_EFF2_HitEffectProc and HEFF_Reset; the effect programs (proc_* through
 * DF_OneHitEffectProc[type]) and their init functions stay interpreted (HitEffectNum is 0 on the Versus stages). */
#include "acnb/port.h"

/* every effect flagged "after" runs its program (HitEffectNum re-read each step) */
void DF_EFF2_HitEffectProcAfter(void)
{
    PS2_FRAME(0x30);
    struct_adbaec9e *p = HitEffect;
    for (int i = 0; i < HitEffectNum; i++, p++)
        if (p->after != 0) gcall(DF_OneHitEffectProc[(int)p->type], p);
}

void DF_EFF2_HitEffectProc(void) {}

/* clears the whole HitEffect[] (ZeroMemory32b's size counts words: 0x1000 -> 0x4000 bytes = 256 x 0x40) */
void HEFF_Reset(void)
{
    PS2_FRAME(0x10);
    ZeroMemory32b(HitEffect, 0x1000);
    HitEffectNum = 0;
}

#ifdef ACNB_SOURCEPORT
/* the original's initialized tables (generated by scripts/sp_datagen.py from the PS2 image) */
void (*DF_OneHitEffectProc[6])(struct struct_adbaec9e *) = {   /* main 0x2600b0 */
    (void (*)(struct struct_adbaec9e *))proc_normal_sprite, proc_zsprite, proc_voice_effect, proc_zsprite_rgbfrm,
    proc_zsprite_rgbfrm2, proc_zsprite_rgbfrm3
};
#endif
